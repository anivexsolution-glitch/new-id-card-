const LANDSCAPE_TO_PORTRAIT: Record<string, string> = Object.fromEntries(
  Object.entries(PORTRAIT_TO_LANDSCAPE).map(([p, l]) => [l, p])
);

export function getPairedTemplateId(
  templateId: string,
  targetOrientation: 'portrait' | 'landscape'
): any {
  if (targetOrientation === 'portrait') {
    if (templateId.startsWith('portrait_')) return templateId;
    return LANDSCAPE_TO_PORTRAIT[templateId] || 'portrait_red_magenta_curved';
  }
  if (templateId.startsWith('landscape_')) return templateId;
  return PORTRAIT_TO_LANDSCAPE[templateId] || 'landscape_red_curved_school';
}

